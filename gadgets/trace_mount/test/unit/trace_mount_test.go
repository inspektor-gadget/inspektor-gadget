type ExpectedTraceMountEvent struct {
	Proc  utils.Process `json:"proc"`
	Op    string        `json:"op"`
	Src   string        `json:"src"`
	Dest  string        `json:"dest"`
	Fs    string        `json:"fs"`
	Data  string        `json:"data"`
	Flags string        `json:"flags"`
	Error string        `json:"error"`
	Call  string        `json:"call"`
}

type mountArgs struct {
	src   string
	dest  string
	fs    string
	flags uintptr
	data  string
}

type testDef struct {
	runnerConfig   *utils.RunnerConfig
	mntnsFilterMap func(info *utils.RunnerInfo) *ebpf.Map
	generateEvent  func(t *testing.T) (mountArgs, error)
	validateEvent  func(t *testing.T, info *utils.RunnerInfo, args mountArgs, events []ExpectedTraceMountEvent)
}

const testSrc = "ig-trace-mount-test"

func expectedMountEvent(info *utils.RunnerInfo, args mountArgs, flags, errStr string) *ExpectedTraceMountEvent {
	proc := info.Proc
	utils.NormalizeParentTid(&proc)
	errno := 0
	if errStr != "" {
		errno = int(unix.ENOENT)
	}
	return &ExpectedTraceMountEvent{
		Proc:  proc,
		Op:    "MOUNT",
		Src:   args.src,
		Dest:  args.dest,
		Fs:    args.fs,
		Data:  args.data,
		Flags: flags,
		Error: errStr,
		Call: fmt.Sprintf(`mount("%s", "%s", "%s", %s, "%s") = %d`,
			args.src, args.dest, args.fs, flags, args.data, errno),
	}
}

// onlyMountEvents drops the umount events generated by the test cleanup.
func onlyMountEvents(events []ExpectedTraceMountEvent) []ExpectedTraceMountEvent {
	var out []ExpectedTraceMountEvent
	for _, e := range events {
		if e.Op == "MOUNT" {
			out = append(out, e)
		}
	}
	return out
}

func TestTraceMountGadget(t *testing.T) {
	gadgettesting.InitUnitTest(t)

	testCases := map[string]testDef{
		"captures_all_events_with_no_filters_configured": {
			runnerConfig:  &utils.RunnerConfig{},
			generateEvent: generateMountEvent,
			validateEvent: func(t *testing.T, info *utils.RunnerInfo, args mountArgs, events []ExpectedTraceMountEvent) {
				utils.ExpectAtLeastOneEvent(func(info *utils.RunnerInfo, _ int) *ExpectedTraceMountEvent {
					return expectedMountEvent(info, args, "MS_NOSUID", "")
				})(t, info, 0, onlyMountEvents(events))
			},
		},
		"captures_no_events_with_no_matching_filter": {
			runnerConfig: &utils.RunnerConfig{},
			mntnsFilterMap: func(info *utils.RunnerInfo) *ebpf.Map {
				return utils.CreateMntNsFilterMap(t, 0)
			},
			generateEvent: generateMountEvent,
			validateEvent: func(t *testing.T, info *utils.RunnerInfo, _ mountArgs, events []ExpectedTraceMountEvent) {
				utils.ExpectNoEvent(t, info, 0, events)
			},
		},
		"captures_events_with_matching_filter": {
			runnerConfig: &utils.RunnerConfig{},
			mntnsFilterMap: func(info *utils.RunnerInfo) *ebpf.Map {
				return utils.CreateMntNsFilterMap(t, info.MountNsID)
			},
			generateEvent: generateMountEvent,
			validateEvent: func(t *testing.T, info *utils.RunnerInfo, args mountArgs, events []ExpectedTraceMountEvent) {
				utils.ExpectOneEvent(func(info *utils.RunnerInfo, _ int) *ExpectedTraceMountEvent {
					return expectedMountEvent(info, args, "MS_NOSUID", "")
				})(t, info, 0, onlyMountEvents(events))
			},
		},
		"captures_failed_mount": {
			runnerConfig: &utils.RunnerConfig{},
			mntnsFilterMap: func(info *utils.RunnerInfo) *ebpf.Map {
				return utils.CreateMntNsFilterMap(t, info.MountNsID)
			},
			generateEvent: generateFailedMountEvent,
			validateEvent: func(t *testing.T, info *utils.RunnerInfo, args mountArgs, events []ExpectedTraceMountEvent) {
				utils.ExpectOneEvent(func(info *utils.RunnerInfo, _ int) *ExpectedTraceMountEvent {
					return expectedMountEvent(info, args, "MS_NOSUID", unix.ErrnoName(unix.ENOENT))
				})(t, info, 0, onlyMountEvents(events))
			},
		},
	}

	for name, testCase := range testCases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			var generated mountArgs
			runner := utils.NewRunnerWithTest(t, testCase.runnerConfig)
			var mntnsFilterMap *ebpf.Map
			if testCase.mntnsFilterMap != nil {
				mntnsFilterMap = testCase.mntnsFilterMap(runner.Info)
			}
			onGadgetRun := func(gadgetCtx operators.GadgetContext) error {
				utils.RunWithRunner(t, runner, func() error {
					var err error
					generated, err = testCase.generateEvent(t)
					return err
				})
				return nil
			}
			normalizeEvent := func(event *ExpectedTraceMountEvent) {
				utils.NormalizeParentTid(&event.Proc)
			}
			opts := gadgetrunner.GadgetRunnerOpts[ExpectedTraceMountEvent]{
				Image:          "trace_mount",
				Timeout:        5 * time.Second,
				MntnsFilterMap: mntnsFilterMap,
				OnGadgetRun:    onGadgetRun,
				NormalizeEvent: normalizeEvent,
			}
			gadgetRunner := gadgetrunner.NewGadgetRunner(t, opts)

			gadgetRunner.RunGadget()

			testCase.validateEvent(t, runner.Info, generated, gadgetRunner.CapturedEvents)
		})
	}
}

// generateMountEvent mounts a tmpfs on a temporary directory and unmounts it.
func generateMountEvent(t *testing.T) (mountArgs, error) {
	args := mountArgs{
		src:   testSrc,
		dest:  t.TempDir(),
		fs:    "tmpfs",
		flags: unix.MS_NOSUID,
		data:  "size=1m",
	}

	if err := unix.Mount(args.src, args.dest, args.fs, args.flags, args.data); err != nil {
		return mountArgs{}, fmt.Errorf("mounting tmpfs on %q: %w", args.dest, err)
	}
	if err := unix.Unmount(args.dest, unix.MNT_DETACH); err != nil {
		return mountArgs{}, fmt.Errorf("unmounting %q: %w", args.dest, err)
	}

	return args, nil
}

// generateFailedMountEvent tries to mount on a non existing directory.
func generateFailedMountEvent(t *testing.T) (mountArgs, error) {
	args := mountArgs{
		src:   testSrc,
		dest:  filepath.Join(t.TempDir(), "does-not-exist"),
		fs:    "tmpfs",
		flags: unix.MS_NOSUID,
		data:  "size=1m",
	}

	err := unix.Mount(args.src, args.dest, args.fs, args.flags, args.data)
	if !errors.Is(err, unix.ENOENT) {
		return mountArgs{}, fmt.Errorf("expected ENOENT mounting on %q, got: %w", args.dest, err)
	}

	return args, nil
}
