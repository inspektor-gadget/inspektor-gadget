"""Generate classperms.go from a pinned Linux SELinux classmap.h.

The parser intentionally accepts only the small C initializer/macro subset used
by security/selinux/include/classmap.h. Unknown tokens and duplicate classes are
fatal so a kernel-source format change cannot silently corrupt the table.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

LINUX_COMMIT = "08df884136f1c1197bab2a27814404fd329d9aac"
SOURCE_PATH = "security/selinux/include/classmap.h"
SOURCE_URL = f"https://github.com/torvalds/linux/blob/{LINUX_COMMIT}/{SOURCE_PATH}"
SOURCE_SHA256 = "a70ba1fa1c79a731579e8bc3ddbac1c3766f0db8ce057d64722e065bc7b8f4cd"


def quoted(text: str) -> list[str]:
    return re.findall(r'"([^"\\]*(?:\\.[^"\\]*)*)"', text)


def parse(source: str) -> list[tuple[str, list[str]]]:
    source = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
    lines = source.splitlines()
    macros: dict[str, list[str]] = {}
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("#define COMMON_"):
            parts = line.split(None, 2)
            if len(parts) != 3:
                raise ValueError(f"malformed macro: {line}")
            name, body = parts[1], parts[2]
            while body.rstrip().endswith("\\"):
                body = body.rstrip()[:-1] + " "
                i += 1
                if i >= len(lines):
                    raise ValueError(f"unterminated macro {name}")
                body += lines[i].strip()
            values: list[str] = []
            for token in re.findall(r'COMMON_[A-Z0-9_]+|"[^"\\]*(?:\\.[^"\\]*)*"', body):
                if token.startswith("COMMON_"):
                    if token not in macros:
                        raise ValueError(f"undefined macro {token} in {name}")
                    values.extend(macros[token])
                else:
                    values.extend(quoted(token))
            macros[name] = values
        i += 1

    marker = "const struct security_class_mapping secclass_map[]"
    if marker not in source:
        raise ValueError("secclass_map initializer not found")
    body = source.split(marker, 1)[1]
    classes: list[tuple[str, list[str]]] = []
    seen: set[str] = set()
    entry_re = re.compile(r'\{\s*"([^"]+)"\s*,\s*\{(.*?)\}\s*\}', re.S)
    for match in entry_re.finditer(body):
        name, initializer = match.groups()
        if name in seen:
            raise ValueError(f"duplicate class {name}")
        seen.add(name)
        values: list[str] = []
        tokens = re.findall(r'COMMON_[A-Z0-9_]+|"[^"\\]*(?:\\.[^"\\]*)*"|NULL', initializer)
        residue = re.sub(r'COMMON_[A-Z0-9_]+|"[^"\\]*(?:\\.[^"\\]*)*"|NULL|[\s,]', '', initializer)
        if residue:
            raise ValueError(f"unknown initializer token(s) for {name}: {residue!r}")
        for token in tokens:
            if token == "NULL":
                continue
            if token.startswith("COMMON_"):
                if token not in macros:
                    raise ValueError(f"undefined macro {token} in class {name}")
                values.extend(macros[token])
            else:
                values.extend(quoted(token))
        if not values or len(values) > 32 or len(values) != len(set(values)):
            raise ValueError(f"invalid permissions for {name}: count={len(values)}")
        classes.append((name, values))
    if not classes:
        raise ValueError("no classes parsed")
    return classes


def generate(classes: list[tuple[str, list[str]]]) -> str:
    lines = [
        "// Copyright 2026 The Inspektor Gadget authors",
        "//",
        "// Licensed under the Apache License, Version 2.0 (the \"License\");",
        "// you may not use this file except in compliance with the License.",
        "// You may obtain a copy of the License at",
        "//",
        "//     http://www.apache.org/licenses/LICENSE-2.0",
        "//",
        "// Unless required by applicable law or agreed to in writing, software",
        "// distributed under the License is distributed on an \"AS IS\" BASIS,",
        "// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.",
        "// See the License for the specific language governing permissions and",
        "// limitations under the License.",
        "",
        "// Code generated by generate_classperms.py; DO NOT EDIT.",
        f"// Source: {SOURCE_URL}",
        f"// Source SHA-256: {SOURCE_SHA256}",
        "",
        "// Package selinuxperms maps SELinux object classes to their ordered",
        "// access-vector permission names, used to decode AVC permission bitmasks.",
        "package selinuxperms",
        "",
        "// ClassPerms maps a SELinux object class to the ordered list of its",
        "// access-vector permissions. The permission at index i corresponds to",
        "// bit (1 << i) in the requested/denied/audited access-vector masks.",
        "var ClassPerms = map[string][]string{",
    ]
    for name, values in classes:
        rendered = ", ".join(f'"{value}"' for value in values)
        lines.append(f'\t"{name}": {{{rendered}}},')
    lines.extend(["}", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = args.source.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SOURCE_SHA256:
        raise SystemExit(f"source SHA-256 mismatch: got {digest}, want {SOURCE_SHA256}")
    generated = generate(parse(raw.decode("utf-8")))
    proc = subprocess.run(["gofmt"], input=generated, text=True, capture_output=True, check=True)
    generated = proc.stdout
    if args.check:
        current = args.output.read_text() if args.output.exists() else ""
        if current != generated:
            print(f"{args.output} is stale; run go generate ./...", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
